"""Generate committed Chinese-only WOFF2 shards; not needed for normal builds.

Usage: python scripts/fonts/subset-chinese.py /path/to/ChillRoundM.ttf
Requires: fonttools[woff]==4.61.1
"""

import argparse
from collections import Counter
from hashlib import sha256
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT_DIR = ROOT / "app/fonts/piggy-zh"
CSS_PATH = ROOT / "css/chinese-fonts.css"
FAMILY = "Piggy Chinese"
SHARD_SIZE = 512
# Exclude Latin, ASCII punctuation, kana and Hangul to preserve existing typography.
CHINESE_RANGES = (
    (0x2E80, 0x2FFF),
    (0x3000, 0x303F),
    (0x3100, 0x312F),
    (0x31A0, 0x31BF),
    (0x31C0, 0x31EF),
    (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF),
    (0xFE10, 0xFE1F),
    (0xFE30, 0xFE4F),
    (0xFF01, 0xFF60),
    (0xFFE0, 0xFFE6),
    (0x20000, 0x323AF),
)


def is_chinese(codepoint):
    return any(start <= codepoint <= end for start, end in CHINESE_RANGES)


def unicode_ranges(codepoints):
    ordered = sorted(codepoints)
    start = end = ordered[0]
    ranges = []
    for codepoint in ordered[1:]:
        if codepoint == end + 1:
            end = codepoint
        else:
            ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
            start = end = codepoint
    ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ", ".join(ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    source = args.source.resolve()
    with TTFont(source) as font:
        available = {codepoint for codepoint in font.getBestCmap() if is_chinese(codepoint)}
    if not available:
        raise ValueError("Source font contains no Chinese characters")

    # Put frequent site characters together, while retaining the entire Chinese cmap
    # for future posts, search results and other dynamic text.
    frequency = Counter()
    for directory in ("app", "components", "data", "layouts", "messages"):
        for path in sorted((ROOT / directory).rglob("*")):
            if path.suffix in {".ts", ".tsx", ".md", ".mdx", ".json"}:
                frequency.update(map(ord, path.read_text(encoding="utf-8")))
    ordered = sorted(available, key=lambda codepoint: (-frequency[codepoint], codepoint))

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    css = [
        "/* Generated by scripts/fonts/subset-chinese.py; do not edit manually.",
        " * Chinese-only derivatives of ChillRoundM 1.805 (SIL OFL 1.1).",
        " * Latin and ASCII punctuation use the existing site fonts.",
        f" * Source SHA-256: {sha256(source.read_bytes()).hexdigest()}",
        " */",
        ":root {",
        f"  --font-zh: '{FAMILY}';",
        "}",
    ]
    seen = set()
    generated_files = set()
    for index, offset in enumerate(range(0, len(ordered), SHARD_SIZE)):
        codepoints = set(ordered[offset : offset + SHARD_SIZE])
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.hinting = False
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(font)

        # OFL reserves ChillRoundM: give modified subsets their own family name.
        names = {
            1: FAMILY,
            2: "Regular",
            3: f"{FAMILY} 1.805 subset {index}",
            4: f"{FAMILY} Regular",
            6: "PiggyChinese-Regular",
            16: FAMILY,
            17: "Regular",
        }
        for record in font["name"].names:
            if record.nameID in names:
                record.string = names[record.nameID].encode(record.getEncoding(), errors="replace")
        font.flavor = "woff2"
        filename = f"piggy-zh-{index:02d}.woff2"
        target = FONT_DIR / filename
        font.save(target)
        font.close()

        with TTFont(target) as saved:
            actual = set(saved.getBestCmap())
            assert actual == codepoints, f"Incorrect cmap in {filename}"
            assert not actual & seen, f"Overlapping cmap in {filename}"
            seen.update(actual)
        generated_files.add(filename)
        css.extend(
            [
                "",
                "@font-face {",
                f"  font-family: '{FAMILY}';",
                f"  src: url('../app/fonts/piggy-zh/{filename}') format('woff2');",
                "  font-style: normal;",
                "  font-weight: 400;",
                "  font-display: swap;",
                f"  unicode-range: {unicode_ranges(codepoints)};",
                "}",
            ]
        )
    assert seen == available, "Chinese glyphs were lost during subsetting"
    # Remove only obsolete shards owned by this generator.
    for old in FONT_DIR.glob("piggy-zh-*.woff2"):
        if old.name not in generated_files:
            old.unlink()
    CSS_PATH.write_text("\n".join(css) + "\n", encoding="utf-8")
    total_bytes = sum((FONT_DIR / name).stat().st_size for name in generated_files)
    print(f"Generated {len(generated_files)} shards, {len(seen)} Chinese characters, {total_bytes:,} bytes")
    print(f"Wrote {CSS_PATH}")


if __name__ == "__main__":
    main()
